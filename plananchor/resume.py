"""Hand-off / resume briefing generation.

After ``/clear`` or a context compaction the agent has *nothing*.  The artefact
produced here is the antidote: a compact, self-contained briefing that can be
pasted straight into a fresh session and gets the agent back to the exact task
it was on.

The briefing is deterministic and offline — no LLM call, no network.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Sequence

from .anchor import AnchorStore
from .drift import DriftReport
from .model import Plan, Severity, Task, TaskStatus

#: Status glyph table used in rendered briefings.
_GLYPH = {
    TaskStatus.PENDING: "[ ]",
    TaskStatus.ACTIVE: "[~]",
    TaskStatus.DONE: "[x]",
    TaskStatus.SKIPPED: "[-]",
    TaskStatus.BLOCKED: "[!]",
}

_LANG = {
    "zh": {
        "title": "会话恢复简报",
        "plan": "计划文件",
        "progress": "整体进度",
        "counts": "任务统计",
        "current": "当前进行中",
        "next": "接下来执行",
        "blocked": "阻塞项",
        "files": "关键文件",
        "done": "已完成",
        "drift": "漂移告警",
        "prompt": "可直接粘贴的恢复提示词",
        "none": "（无）",
        "generated": "由 PlanAnchor 自动生成",
        "resume_hint": "继续按计划执行下一个任务；先读取下方关键文件，再开始改动。",
    },
    "en": {
        "title": "Session Resume Briefing",
        "plan": "Plan file",
        "progress": "Overall progress",
        "counts": "Task counts",
        "current": "Currently in progress",
        "next": "Up next",
        "blocked": "Blockers",
        "files": "Key files",
        "done": "Completed",
        "drift": "Drift warnings",
        "prompt": "Copy-paste resume prompt",
        "none": "(none)",
        "generated": "Auto-generated by PlanAnchor",
        "resume_hint": "Resume the next task in the plan; read the key files below before editing.",
    },
}


@dataclass
class ResumeBrief:
    """Structured resume briefing (also renderable as Markdown)."""

    title: str = ""
    plan_path: str = ""
    progress: float = 0.0
    counts: Dict[str, int] = field(default_factory=dict)
    current: List[Task] = field(default_factory=list)
    next_tasks: List[Task] = field(default_factory=list)
    blocked: List[Task] = field(default_factory=list)
    done: List[Task] = field(default_factory=list)
    files: List[str] = field(default_factory=list)
    drift: List[str] = field(default_factory=list)
    snapshot_seq: int = 0
    lang: str = "zh"

    def to_dict(self) -> Dict[str, object]:
        return {
            "title": self.title,
            "plan_path": self.plan_path,
            "progress": self.progress,
            "counts": self.counts,
            "current": [_brief_task(t) for t in self.current],
            "next": [_brief_task(t) for t in self.next_tasks],
            "blocked": [_brief_task(t) for t in self.blocked],
            "done": [_brief_task(t) for t in self.done],
            "files": self.files,
            "drift": self.drift,
            "snapshot_seq": self.snapshot_seq,
            "lang": self.lang,
        }

    def render(self, *, with_prompt: bool = True) -> str:
        """Render the briefing as Markdown."""
        return render_brief(self, with_prompt=with_prompt)


def _brief_task(t: Task) -> Dict[str, object]:
    return {
        "uid": t.uid,
        "title": t.title,
        "status": t.status.value,
        "section": t.section,
        "refs": list(t.refs),
        "symbols": list(t.symbols),
        "note": t.note,
    }


# --------------------------------------------------------------------------- #
# Public API
# --------------------------------------------------------------------------- #

def build_resume(
    plan: Plan,
    *,
    store: Optional[AnchorStore] = None,
    drift: Optional[DriftReport] = None,
    lang: str = "zh",
    next_count: int = 3,
    done_count: int = 8,
) -> ResumeBrief:
    """Build a resume briefing from the current plan state.

    Args:
        plan: Parsed plan.
        store: Optional anchor store; used to report the recovery baseline.
        drift: Optional drift report; high severity items are surfaced.
        lang: ``"zh"`` (default) or ``"en"``.
        next_count: How many upcoming tasks to include.
        done_count: How many recently completed tasks to include.

    Returns:
        A :class:`ResumeBrief`.
    """
    lang = lang if lang in _LANG else "zh"
    tasks = plan.all_tasks()

    current = [t for t in tasks if t.status is TaskStatus.ACTIVE]
    blocked = [t for t in tasks if t.status is TaskStatus.BLOCKED]
    pending = [t for t in tasks if t.status is TaskStatus.PENDING and not t.children]
    done = [t for t in tasks if t.status is TaskStatus.DONE and not t.children]

    # ``next`` prefers pending leaf tasks, keeping document order.
    ordered_next = sorted(pending, key=lambda t: t.line)[:next_count]

    # Key files: everything referenced by open or in-flight work, de-duplicated.
    files: List[str] = []
    for t in current + ordered_next + blocked:
        for ref in t.refs:
            if ref not in files:
                files.append(ref)

    drift_lines: List[str] = []
    if drift is not None:
        for item in drift.items:
            if item.severity in (Severity.ERROR, Severity.WARNING):
                drift_lines.append("[%s] %s" % (item.rule, item.message))

    seq = 0
    if store is not None and store.exists():
        latest = store.latest()
        if latest is not None:
            seq = latest.seq

    return ResumeBrief(
        title=plan.title or os.path.basename(plan.path or "plan"),
        plan_path=plan.path,
        progress=plan.progress(),
        counts=plan.counts(),
        current=current,
        next_tasks=ordered_next,
        blocked=blocked,
        done=sorted(done, key=lambda t: t.line)[-done_count:],
        files=files,
        drift=drift_lines,
        snapshot_seq=seq,
        lang=lang,
    )


def render_brief(brief: ResumeBrief, *, with_prompt: bool = True) -> str:
    """Render a :class:`ResumeBrief` as Markdown."""
    L = _LANG.get(brief.lang, _LANG["zh"])
    out: List[str] = []
    add = out.append

    add("# %s — %s" % (L["title"], brief.title))
    add("")
    add("> %s · snapshot #%d" % (L["generated"], brief.snapshot_seq))
    add("")
    add("| %s | %s |" % (L["plan"], "`%s`" % brief.plan_path if brief.plan_path else L["none"]))
    add("|---|---|")
    add("| %s | **%.1f%%** |" % (L["progress"], brief.progress))
    counts = brief.counts
    add(
        "| %s | done %d · active %d · pending %d · blocked %d · skipped %d |"
        % (
            L["counts"],
            counts.get("done", 0),
            counts.get("active", 0),
            counts.get("pending", 0),
            counts.get("blocked", 0),
            counts.get("skipped", 0),
        )
    )
    add("")

    add("## 🔄 %s" % L["current"])
    add("")
    if brief.current:
        for t in brief.current:
            add("- `%s` %s — %s" % (t.uid, t.title, _refs_of(t)))
    else:
        add("- %s" % L["none"])
    add("")

    add("## ⏭️ %s" % L["next"])
    add("")
    if brief.next_tasks:
        for t in brief.next_tasks:
            add("- `%s` %s — %s" % (t.uid, t.title, _refs_of(t)))
    else:
        add("- %s" % L["none"])
    add("")

    if brief.blocked:
        add("## 🚧 %s" % L["blocked"])
        add("")
        for t in brief.blocked:
            add("- `%s` %s%s" % (t.uid, t.title, " — %s" % t.note if t.note else ""))
        add("")

    if brief.files:
        add("## 📁 %s" % L["files"])
        add("")
        for f in brief.files:
            add("- `%s`" % f)
        add("")

    if brief.done:
        add("## ✅ %s" % L["done"])
        add("")
        for t in brief.done[-8:]:
            add("- `%s` %s" % (t.uid, t.title))
        add("")

    if brief.drift:
        add("## ⚠️ %s" % L["drift"])
        add("")
        for line in brief.drift[:10]:
            add("- %s" % line)
        add("")

    if with_prompt:
        add("## 🧾 %s" % L["prompt"])
        add("")
        add("```text")
        add(_prompt_block(brief))
        add("```")
        add("")

    return "\n".join(out)


def _refs_of(t: Task) -> str:
    """Render the reference part of a briefing line."""
    parts: List[str] = []
    if t.refs:
        parts.append(", ".join("`%s`" % r for r in t.refs))
    if t.symbols:
        parts.append("#" + ", #".join(t.symbols))
    if t.note:
        parts.append(t.note)
    return " · ".join(parts) if parts else "-"


def _prompt_block(brief: ResumeBrief) -> str:
    """Build the copy-paste prompt for a fresh session."""
    zh = brief.lang == "zh"
    lines: List[str] = []
    if zh:
        lines.append("你正在接续一个被中断的编码会话。请严格按以下上下文恢复工作：")
        lines.append("")
        lines.append("计划文件：%s" % (brief.plan_path or "PLAN.md"))
        lines.append("当前进度：%.1f%%" % brief.progress)
        if brief.current:
            lines.append(
                "中断时正在执行：%s"
                % "；".join("%s %s" % (t.uid, t.title) for t in brief.current)
            )
        if brief.next_tasks:
            lines.append(
                "接下来依次执行：%s"
                % "；".join("%s %s" % (t.uid, t.title) for t in brief.next_tasks)
            )
        if brief.blocked:
            lines.append(
                "已知阻塞：%s"
                % "；".join("%s %s" % (t.uid, t.note or t.title) for t in brief.blocked)
            )
        if brief.files:
            lines.append("优先阅读这些文件：%s" % "、".join(brief.files))
        lines.append("")
        lines.append("要求：先打开计划文件确认任务状态，再开始改动；完成一项就把 `- [ ]` 改为 `- [x]`，"
                     "并在每次阶段性完成后运行 `plananchor snapshot` 保存锚点。")
    else:
        lines.append("You are resuming an interrupted coding session. Use this context:")
        lines.append("")
        lines.append("Plan file: %s" % (brief.plan_path or "PLAN.md"))
        lines.append("Progress: %.1f%%" % brief.progress)
        if brief.current:
            lines.append(
                "Was working on: %s"
                % "; ".join("%s %s" % (t.uid, t.title) for t in brief.current)
            )
        if brief.next_tasks:
            lines.append(
                "Next in order: %s"
                % "; ".join("%s %s" % (t.uid, t.title) for t in brief.next_tasks)
            )
        if brief.blocked:
            lines.append(
                "Known blockers: %s"
                % "; ".join("%s %s" % (t.uid, t.note or t.title) for t in brief.blocked)
            )
        if brief.files:
            lines.append("Read these files first: %s" % ", ".join(brief.files))
        lines.append("")
        lines.append("Resume the next task in the plan; read the key files first, then edit. "
                     "Flip `- [ ]` to `- [x]` when a task is done, and run `plananchor snapshot` "
                     "after each milestone.")
    return "\n".join(lines)
